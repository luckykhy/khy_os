/**
 * 替换敏感词为同义词
 * @param {string} text - 原始文本
 * @param {number} replaceRatio - 替换比例 (0-1)，默认 0.5
 * @returns {string} 替换后的文本
 */
function replaceSynonyms(text, replaceRatio = 0.5) {
  if (!text || text.trim().length === 0) {
    return text;
  }

  let result = text;

  // 按关键词长度降序排序（先替换长的，避免短词干扰）
  const sortedEntries = Object.entries(SYNONYM_MAP).sort((a, b) => b[0].length - a[0].length);

  for (const [word, synonyms] of sortedEntries) {
    if (result.includes(word)) {
      // 根据替换比例决定是否替换这个词
      if (Math.random() < replaceRatio) {
        const synonym = synonyms[Math.floor(Math.random() * synonyms.length)];
        result = result.replace(new RegExp(_escapeRegExp(word), 'g'), synonym);
      }
    }
  }

  // 后处理：去除连续重复的词（如"程序程序"→"程序"）
  result = result.replace(/(.{2,})\1+/g, '$1');

  return result;
}

/**
 * 生成完全同义替换的 prompt（更高替换比例）
 * @param {string} text - 原始文本
 * @returns {string}
 */
function replaceSynonymsAggressive(text) {
  return replaceSynonyms(text, 0.9);
}

/**
 * 生成轻微同义替换的 prompt（保留更多原词）
 * @param {string} text - 原始文本
 * @returns {string}
 */
function replaceSynonymsLight(text) {
  return replaceSynonyms(text, 0.3);
}

/**
 * 转义正则特殊字符
 */
function _escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * 获取某个词的所有同义词
 * @param {string} word
 * @returns {string[]}
 */
function getSynonyms(word) {
  return SYNONYM_MAP[word] || [];
}


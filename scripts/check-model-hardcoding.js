#!/usr/bin/env node
/**
 * Model-name hardcoding checker (machine-enforced model-name single source of truth).
 *
 * Derives the watch-set straight from services/backend/src/constants/models.js (the
 * SSOT typed arrays) and runs changed (or explicitly passed) files through the pure
 * `assessFile` guard in scripts/lib/modelHardcodingGuard.js. Any standalone quoted
 * model-name literal that reappears in business logic — outside the data-catalog
 * allowlist — gets caught at commit time, so the "switch a model = edit one place"
 * guarantee keeps holding instead of silently rotting back into scattered literals.
 *
 * Usage:
 *   node scripts/check-model-hardcoding.js --changed
 *   node scripts/check-model-hardcoding.js --changed --strict-warnings
 *   node scripts/check-model-hardcoding.js <file-or-dir> [more...]
 */
'use strict';

const fs = require('fs');
const path = require('path');
const cp = require('child_process');

const guard = require('./lib/modelHardcodingGuard');

const cwd = process.cwd();
const args = process.argv.slice(2);
const strictWarnings = args.includes('--strict-warnings');
const changedMode = args.includes('--changed');
const rawTargets = args.filter((a) => !a.startsWith('--'));

// 只扫 JS 源(模型名硬编码是 JS 逻辑问题)。
const TEXT_EXTS = new Set(['.js', '.cjs', '.mjs']);

const IGNORE_DIRS = new Set([
  '.git', 'node_modules', 'dist', 'build', '.cache', '.tmp', 'coverage', 'logs',
  // Derived/generated snapshots (regenerated by setup.py on wheel build) — not source.
  // 扫这些等于扫旧 wheel 快照(陈旧、改了也被重拷覆盖),只会刷出过时的误报。
  'bundled', '_source',
]);

// SSOT 模块位置(从仓库根解析)。读不到 → 空监视名单 → 守卫静默放行(fail-soft)。
const MODELS_MODULE = path.resolve(cwd, 'services/backend/src/constants/models.js');

function loadWatchedNames() {
  try {
    // 清缓存确保拿到磁盘当前内容(本进程内可能多次调用)。
    delete require.cache[require.resolve(MODELS_MODULE)];
    return guard.deriveWatchedNames(require(MODELS_MODULE));
  } catch {
    return [];
  }
}

function run(cmd) {
  try {
    return cp.execSync(cmd, { cwd, stdio: ['ignore', 'pipe', 'pipe'], encoding: 'utf8' }).trim();
  } catch {
    return '';
  }
}

function listChangedFiles() {
  const baseRef = String(process.env.GIT_BASE_REF || '').trim();
  if (baseRef) {
    const out = run(`git diff --name-only --diff-filter=ACMR ${baseRef}...HEAD`);
    if (out) return out.split('\n').map((s) => s.trim()).filter(Boolean);
  }
  const staged = run('git diff --name-only --cached --diff-filter=ACMR');
  if (staged) return staged.split('\n').map((s) => s.trim()).filter(Boolean);
  const head = run('git diff --name-only --diff-filter=ACMR HEAD');
  if (head) return head.split('\n').map((s) => s.trim()).filter(Boolean);
  return [];
}

function shouldIgnore(filePath) {
  return String(filePath).split(path.sep).some((p) => IGNORE_DIRS.has(p));
}

function collectFilesFromTarget(targetPath, out) {
  const full = path.resolve(cwd, targetPath);
  if (!fs.existsSync(full)) return;
  const st = fs.statSync(full);
  if (st.isDirectory()) {
    for (const entry of fs.readdirSync(full)) {
      collectFilesFromTarget(path.join(targetPath, entry), out);
    }
    return;
  }
  const rel = path.relative(cwd, full);
  if (shouldIgnore(rel)) return;
  // 跳过测试文件:测试里出现模型名字面量是断言固定值,合法。
  const base = path.basename(rel);
  if (/\.test\.(js|cjs|mjs)$/.test(base)) return;
  if (!TEXT_EXTS.has(path.extname(rel))) return;
  out.add(rel.replace(/\\/g, '/'));
}

function gatherFiles() {
  const out = new Set();
  if (changedMode) {
    for (const rel of listChangedFiles()) collectFilesFromTarget(rel, out);
  }
  for (const t of rawTargets) collectFilesFromTarget(t, out);
  return [...out];
}

function checkFile(relPath, watchedNames, findings) {
  let source = '';
  try {
    source = fs.readFileSync(path.resolve(cwd, relPath), 'utf8');
  } catch {
    return;
  }
  const result = guard.assessFile({ relPath, source, watchedNames });
  for (const f of (result && result.findings) || []) {
    findings.push({ ...f, file: relPath });
  }
}

function printFindings(findings) {
  if (findings.length === 0) {
    console.log('Model-hardcoding check passed: no scattered model-name literals found.');
    return;
  }
  for (const f of findings) {
    const prefix = f.severity === 'error' ? 'ERROR' : 'WARN ';
    console.log(`[${prefix}] ${f.rule} ${f.file}:${f.line}`);
    console.log(`  ${f.message}`);
    if (f.snippet) console.log(`  ${f.snippet}`);
  }
  const errorCount = findings.filter((f) => f.severity === 'error').length;
  const warnCount = findings.filter((f) => f.severity === 'warning').length;
  console.log(`\nSummary: ${errorCount} error(s), ${warnCount} warning(s).`);
}

function main() {
  const watchedNames = loadWatchedNames();
  const files = gatherFiles();
  if (files.length === 0) {
    console.log('No target files found. Use --changed or pass file/directory paths.');
    process.exit(0);
  }
  const findings = [];
  for (const file of files) checkFile(file, watchedNames, findings);
  printFindings(findings);

  const hasError = findings.some((f) => f.severity === 'error');
  const hasWarn = findings.some((f) => f.severity === 'warning');
  if (hasError || (strictWarnings && hasWarn)) {
    process.exit(1);
  }
}

main();
